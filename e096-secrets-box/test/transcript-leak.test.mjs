// e096 — the test the RFC asked for: prove the value never reaches the transcript.
//
// A canary value goes in through exactly the path the browser panel uses
// (peer operation -> vault CLI), and we assert it is nowhere it must not be:
//   - not in the peer's response
//   - not in anything this process printed
//   - not in the child's argv or environment (recorded by a wrapper around the vault)
//   - not in cleartext in the vault file (which must be 0600)
//   - not in any *.jsonl (session transcripts) under the workspace or the PI WEB data dir
// and it IS recoverable from the vault with the passphrase.
//
// Dummy values only, by construction: every value here is generated by this test.

import test from "node:test";
import assert from "node:assert/strict";
import { execFileSync, spawnSync } from "node:child_process";
import { chmodSync, existsSync, mkdtempSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { randomUUID } from "node:crypto";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = resolve(fileURLToPath(import.meta.url), "..");
const ROOT = resolve(HERE, "..");
const REAL_VAULT = join(ROOT, "vault", "vault");

const tmp = mkdtempSync(join(tmpdir(), "e096-"));
const vaultFile = join(tmp, "vault.enc");
const argvLog = join(tmp, "child-argv.txt");
const envLog = join(tmp, "child-environ.txt");
const wrapper = join(tmp, "vault-wrapper.sh");
const needsPath = join(tmp, "needs.json");

// A wrapper that records what the child actually sees, then execs the real vault.
// NB: /proc/$$ (the shell), not /proc/self — the redirection is performed by
// `tr`, so /proc/self would report tr's own argv.
writeFileSync(wrapper, `#!/usr/bin/env bash
tr '\\0' ' ' < /proc/$$/cmdline > ${argvLog}
tr '\\0' '\\n' < /proc/$$/environ > ${envLog}
exec ${REAL_VAULT} "$@"
`);
chmodSync(wrapper, 0o755);

writeFileSync(needsPath, JSON.stringify({
  vault_cli: wrapper,
  vault_file: vaultFile,
  vault_backend: "age",
}, null, 2));

// Point the module at the temp config BEFORE importing it.
process.env.SECRETS_BOX_NEEDS = needsPath;
const { handleOperation } = await import("../src/server.mjs");

const PASS = `dummy-passphrase-${randomUUID()}`;
const CANARY = `CANARY-${randomUUID()}`;
const NAME = "E096_TEST_KEY";

/** Capture everything this process writes while `fn` runs. */
async function capture(fn) {
  const out = [];
  const origLog = console.log, origErr = console.error, origWarn = console.warn;
  const origWrite = process.stdout.write.bind(process.stdout);
  const origErrWrite = process.stderr.write.bind(process.stderr);
  console.log = (...a) => out.push(a.join(" "));
  console.error = (...a) => out.push(a.join(" "));
  console.warn = (...a) => out.push(a.join(" "));
  process.stdout.write = (chunk, ...rest) => { out.push(String(chunk)); return origWrite(chunk, ...rest); };
  process.stderr.write = (chunk, ...rest) => { out.push(String(chunk)); return origErrWrite(chunk, ...rest); };
  try {
    return { result: await fn(), printed: out.join("\n") };
  } finally {
    console.log = origLog; console.error = origErr; console.warn = origWarn;
    process.stdout.write = origWrite; process.stderr.write = origErrWrite;
  }
}

function jsonlFilesUnder(dir, acc = [], depth = 0) {
  if (depth > 4 || !existsSync(dir)) return acc;
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, entry.name);
    if (entry.isDirectory()) jsonlFilesUnder(p, acc, depth + 1);
    else if (entry.name.endsWith(".jsonl")) acc.push(p);
  }
  return acc;
}

function grepFiles(files, needle) {
  const hits = [];
  for (const f of files) {
    try {
      if (readFileSync(f, "utf8").includes(needle)) hits.push(f);
    } catch {
      // unreadable/binary: skip
    }
  }
  return hits;
}

test("store: the value round-trips through the vault", async () => {
  const { result } = await capture(() => handleOperation("store", { name: NAME, value: CANARY, passphrase: PASS }));
  assert.equal(result.ok, true, JSON.stringify(result));
  assert.equal(result.name, NAME);
  assert.ok(!JSON.stringify(result).includes(CANARY), "the peer response must never echo the value");
});

test("store: the value is nowhere it must not be", () => {
  // vault file: exists, 0600, encrypted (no cleartext canary)
  assert.ok(existsSync(vaultFile), "the vault file was not created");
  assert.equal(statSync(vaultFile).mode & 0o777, 0o600, "the vault file must be mode 0600");
  assert.ok(!readFileSync(vaultFile, "utf8").includes(CANARY), "the vault file leaks the value in cleartext");
  assert.ok(statSync(vaultFile).size > 100, "the vault file looks empty");

  // the child process: argv and environment (recorded by the wrapper)
  const argv = readFileSync(argvLog, "utf8");
  const environ = readFileSync(envLog, "utf8");
  assert.ok(!argv.includes(CANARY), `the value reached the child's argv: ${argv}`);
  assert.ok(!argv.includes(PASS), `the passphrase reached the child's argv: ${argv}`);
  assert.ok(!environ.includes(CANARY), "the value reached the child's environment");
  assert.ok(!environ.includes(PASS), "the passphrase reached the child's environment");
  assert.ok(argv.includes("--value-fd"), "expected the value on a file descriptor");

  // transcripts: no session JSONL anywhere we can see mentions the canary
  const watched = [
    join(ROOT, ".pi-web"),
    "/home/vuos/.pi-web",
    join(ROOT, "test"),
  ];
  const jsonls = watched.flatMap((d) => jsonlFilesUnder(d));
  assert.ok(jsonls.length > 0, "no transcript JSONL files found to check (test is not proving much)");
  assert.deepEqual(grepFiles(jsonls, CANARY), [], "the canary appears in a session transcript");
});

/** Run the vault from a shell with the passphrase on fd 3 (the fd path, real CLI). */
function vaultWithPassphrase(args, passphrase) {
  return spawnSync("bash", ["-c", `${REAL_VAULT} "$@" 3<<<"$SB_PASS"`, "bash", ...args], {
    env: {
      ...process.env,
      VAULT_FILE: vaultFile,
      VAULT_BACKEND: "age",
      VAULT_PASSPHRASE: "",
      VAULT_TEST_VALUE: "",
      SB_PASS: passphrase,
    },
    encoding: "utf8",
    stdio: ["ignore", "pipe", "pipe"],
  });
}

test("store: the value is recoverable, and the passphrase is the gate", () => {
  const ok = vaultWithPassphrase(["get", NAME, "--passphrase-fd", "3"], PASS);
  assert.equal(ok.status, 0, `get failed: ${ok.stderr}`);
  assert.equal(ok.stdout, CANARY, "the stored value does not round-trip");

  const bad = vaultWithPassphrase(["get", NAME, "--passphrase-fd", "3"], `wrong-${randomUUID()}`);
  assert.notEqual(bad.status, 0, "a wrong passphrase must not decrypt");
  assert.ok(!bad.stderr.includes("wrong-"), "the failure must not echo the passphrase back");

  const empty = vaultWithPassphrase(["get", NAME, "--passphrase-fd", "3"], "");
  assert.notEqual(empty.status, 0, "an empty passphrase must not decrypt");
});

test("list: names come back, values never do", async () => {
  const { result, printed } = await capture(() => handleOperation("list", { passphrase: PASS }));
  assert.equal(result.ok, true, JSON.stringify(result));
  assert.ok(result.names.includes(NAME), `expected ${NAME} in ${JSON.stringify(result.names)}`);
  assert.ok(!JSON.stringify(result).includes(CANARY), "list leaked a value");
  assert.ok(!printed.includes(CANARY), `list printed the value: ${printed}`);

  const { result: bad } = await capture(() => handleOperation("list", { passphrase: "wrong" }));
  assert.equal(bad.ok, false);
  assert.ok(!JSON.stringify(bad).includes("wrong-pass"), "the passphrase was echoed back");
});

test("empty input is refused without touching the vault", async () => {
  assert.equal((await handleOperation("store", { name: "bad name!", value: CANARY, passphrase: PASS })).ok, false);
  assert.equal((await handleOperation("store", { name: NAME, value: "", passphrase: PASS })).ok, false);
  assert.equal((await handleOperation("store", { name: NAME, value: CANARY, passphrase: "" })).ok, false);
  await assert.rejects(() => handleOperation("nope", {}));
});

test("policy: the server module never logs, so there is nothing to leak", () => {
  const src = readFileSync(join(ROOT, "src", "server.mjs"), "utf8");
  const logs = src.match(/console\.\w+/g) ?? [];
  assert.deepEqual(logs, [], `server.mjs must not log anything (found ${logs.join(", ")})`);
  // and it must pass the secrets on descriptors, not argv
  assert.ok(src.includes('"--value-fd", "0"'), "the value must go to fd 0");
  assert.ok(src.includes('"--passphrase-fd", "3"'), "the passphrase must go to fd 3");
});

test.after(() => {
  rmSync(tmp, { recursive: true, force: true });
});
